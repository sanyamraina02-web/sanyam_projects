/**
 * Generate public/sitemap.xml from the static page list + every blog post in
 * src/content/blog/.
 *
 *   node scripts/generate-sitemap.js
 */

import { readdirSync, readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const BLOG_DIR = join(__dirname, '..', 'src', 'content', 'blog')
const OUT = join(__dirname, '..', 'public', 'sitemap.xml')

const SITE = 'https://www.volumetree.com'
const TODAY = new Date().toISOString().split('T')[0]

const staticUrls = [
  { loc: '/', priority: '1.0', changefreq: 'weekly' },
  { loc: '/launch-in-30-days', priority: '0.9', changefreq: 'monthly' },
  { loc: '/enterprise-ai-engineering', priority: '0.9', changefreq: 'monthly' },
  { loc: '/workshops', priority: '0.8', changefreq: 'monthly' },
  { loc: '/case-studies', priority: '0.8', changefreq: 'monthly' },
  { loc: '/blog', priority: '0.7', changefreq: 'daily' },
  { loc: '/about', priority: '0.6', changefreq: 'monthly' },
  { loc: '/ebook', priority: '0.6', changefreq: 'monthly' },
  { loc: '/contact', priority: '0.7', changefreq: 'monthly' },
]

function readFrontmatterDate(md) {
  const m = md.match(/^---\s*([\s\S]*?)\s*---/)
  if (!m) return null
  const dateMatch = m[1].match(/^date:\s*(.+)$/m)
  return dateMatch ? dateMatch[1].trim().replace(/^["']|["']$/g, '') : null
}

function collectBlogUrls() {
  return readdirSync(BLOG_DIR)
    .filter((f) => f.endsWith('.md'))
    .map((f) => {
      const slug = f.replace(/\.md$/, '')
      const md = readFileSync(join(BLOG_DIR, f), 'utf8')
      const date = readFrontmatterDate(md) || TODAY
      return { loc: `/blog/${slug}`, lastmod: date, priority: '0.6', changefreq: 'monthly' }
    })
    .sort((a, b) => (a.lastmod < b.lastmod ? 1 : -1))
}

function buildUrl({ loc, lastmod = TODAY, priority, changefreq }) {
  return `  <url>
    <loc>${SITE}${loc}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`
}

const blogUrls = collectBlogUrls()
const all = [
  ...staticUrls.map((u) => ({ ...u, lastmod: TODAY })),
  ...blogUrls,
]

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Sitemap — Volumetree
  Generated by scripts/generate-sitemap.js — re-run after blog or page changes.
  Update SITE in the script to your real production domain.
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${all.map(buildUrl).join('\n')}
</urlset>
`

writeFileSync(OUT, xml, 'utf8')
console.log(`Wrote ${OUT}`)
console.log(`  static pages: ${staticUrls.length}`)
console.log(`  blog posts:   ${blogUrls.length}`)
console.log(`  total URLs:   ${all.length}`)
